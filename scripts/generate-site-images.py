"""Generate portfolio sharing/icons and record intrinsic public image sizes.

Run with python3 scripts/generate-site-images.py (requires Pillow and DejaVu Sans).
"""
from pathlib import Path
import json
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / 'public'
FONT = Path('/usr/share/fonts/truetype/dejavu')


def font(size, bold=False):
    return ImageFont.truetype(str(FONT / ('DejaVuSans-Bold.ttf' if bold else 'DejaVuSans.ttf')), size)


og = Image.new('RGB', (1200, 630), '#0a0a0a')
draw = ImageDraw.Draw(og)
draw.rounded_rectangle((64, 64, 72, 566), radius=4, fill='#3ad2f2')
draw.text((108, 112), 'CHRISTOPHER VELEZ', font=font(52, True), fill='#ffffff')
draw.text((108, 228), 'Robotics, embedded foundations', font=font(42), fill='#ffffff')
draw.text((108, 290), '& AI / XR interactive systems', font=font(42), fill='#ffffff')
draw.text((108, 478), 'SJSU · B.S. Computer Engineering student', font=font(28), fill='#b5b5b5')
og.save(PUBLIC / 'images/og-default.png', optimize=True)

# CV letterforms rendered at high resolution for crisp small-size icons.
icon = Image.new('RGB', (720, 720), '#070b17')
draw = ImageDraw.Draw(icon)
draw.text((360, 348), 'CV', anchor='mm', font=font(360, True), fill='#75f0ff')
icon.resize((180, 180), Image.Resampling.LANCZOS).save(PUBLIC / 'apple-touch-icon.png')
icon.resize((32, 32), Image.Resampling.LANCZOS).save(PUBLIC / 'favicon.png')
icon.save(PUBLIC / 'favicon.ico', sizes=[(16, 16), (32, 32), (48, 48)])

sizes = {}
for path in sorted((PUBLIC / 'images').rglob('*')):
    if path.is_file():
        with Image.open(path) as image:
            sizes['/' + path.relative_to(PUBLIC).as_posix()] = dict(width=image.width, height=image.height)
(ROOT / 'src/utils/imageDimensions.ts').write_text(
    '// Generated by scripts/generate-site-images.py; rerun when public images change.\n'
    + 'export const imageDimensions: Record<string, { width: number; height: number }> = '
    + json.dumps(sizes, indent=2) + ';\n'
)
